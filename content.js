    const strengths = known.slice().sort(function (a, b) { return b.index - a.index; })
      .filter(function (d) { return limits.indexOf(d) === -1; }).slice(0, 3);
    return { index: toIndex(overall), level: levelOf(overall), directions: directions, limits: limits, strengths: strengths };
